import { z } from 'zod';
import { decimalString } from './catalog.js';

/**
 * Tender methods that settle immediately (used for customer payments, expenses). Sales and refunds also accept
 * CUSTOMER_CREDIT - see `saleTenderMethods`.
 */
export const tenderMethods = ['CASH', 'CARD', 'BANK_TRANSFER'] as const;
export type TenderMethod = (typeof tenderMethods)[number];

/**
 * Methods accepted on a SALE or a REFUND. `CUSTOMER_CREDIT` puts the amount on the customer's account (Phase 6):
 * it needs a customer with a credit limit and is enforced inside the sale transaction.
 */
export const saleTenderMethods = ['CASH', 'CARD', 'BANK_TRANSFER', 'CUSTOMER_CREDIT'] as const;
export type SaleTenderMethod = (typeof saleTenderMethods)[number];

/** Quantity: > 0, at most 3 decimals (matches Decimal(14,3)). */
const quantityString = z
  .string()
  .trim()
  .regex(/^\d{1,11}(\.\d{1,3})?$/, 'Quantity must be a positive number with at most 3 decimals')
  .refine((v) => /[1-9]/.test(v), 'Quantity must be greater than zero');

/** Money to 2 decimals. */
const moneyString = z
  .string()
  .trim()
  .regex(/^\d{1,14}(\.\d{1,2})?$/, 'Amount must be a plain number with at most 2 decimals');

const percentString = decimalString().refine(
  (v) => /^(\d{1,2}(\.\d+)?|100(\.0+)?)$/.test(v),
  'Cannot exceed 100',
);

const refineNoDoubleDiscount = <T extends { discountPercent?: string; discountAmount?: string }>(
  data: T,
  ctx: z.RefinementCtx,
) => {
  const hasPercent = data.discountPercent !== undefined && /[1-9]/.test(data.discountPercent);
  const hasAmount = data.discountAmount !== undefined && /[1-9]/.test(data.discountAmount);
  if (hasPercent && hasAmount) {
    ctx.addIssue({
      code: 'custom',
      message: 'Provide either a discount percentage or a fixed discount amount, not both.',
      path: ['discountAmount'],
    });
  }
};

/** Voucher codes are typed or scanned: letters, digits, dash. Stored upper-case. */
export const voucherCode = z
  .string()
  .trim()
  .min(3)
  .max(32)
  .regex(/^[A-Za-z0-9-]+$/, 'Use letters, digits and dashes only')
  .transform((v) => v.toUpperCase());

export const saleLineSchema = z
  .object({
    productId: z.string().trim().min(1),
    quantity: quantityString,
    /** Price override. Requires the `price.change` permission; otherwise the product's selling price is used. */
    unitPrice: decimalString().optional(),
    discountPercent: percentString.optional(),
    discountAmount: moneyString.optional(),
    /** Salesman who made this sale line (commission / reporting). */
    salesman: z.string().trim().max(40).optional(),
  })
  .superRefine(refineNoDoubleDiscount);
export type SaleLineBody = z.infer<typeof saleLineSchema>;

export const createSaleSchema = z
  .object({
    /** Idempotency key generated by the client for this checkout. Re-sending it returns the SAME sale. */
    clientRequestId: z.string().trim().min(8).max(64),
    storeId: z.string().trim().min(1),
    /** Optional customer (required when any payment is CUSTOMER_CREDIT). */
    customerId: z.string().trim().min(1).optional(),
    items: z.array(saleLineSchema).min(1, 'A sale must have at least one item').max(200),
    discountPercent: percentString.optional(),
    discountAmount: moneyString.optional(),
    payments: z
      .array(
        z.object({
          method: z.enum(saleTenderMethods),
          amount: moneyString,
          reference: z.string().trim().max(64).optional(),
        }),
      )
      .max(6),
    customerName: z.string().trim().max(120).optional(),
    customerPhone: z.string().trim().max(32).optional(),
    notes: z.string().trim().max(500).optional(),
    /** Document references from the POS header. */
    orderRef: z.string().trim().max(40).optional(),
    fbrInvoiceNo: z.string().trim().max(40).optional(),
    creditNoteRef: z.string().trim().max(40).optional(),
    /** Charges added on top of the items. */
    serviceFee: moneyString.optional(),
    otherCharges: moneyString.optional(),
    /** Round the payable amount to a whole number (the server works out the rounding amount). */
    roundToWhole: z.boolean().optional(),
    /** Codes of a discount voucher and a credit memo to redeem against this sale. */
    discountVoucherCode: voucherCode.optional(),
    creditMemoCode: voucherCode.optional(),
  })
  .superRefine(refineNoDoubleDiscount);
export type CreateSaleInput = z.infer<typeof createSaleSchema>;

export const saleListQuerySchema = z.object({
  search: z.string().trim().max(120).optional(),
  storeId: z.string().trim().min(1).optional(),
  customerId: z.string().trim().min(1).optional(),
  status: z.enum(['COMPLETED', 'PARTIALLY_REFUNDED', 'REFUNDED', 'VOID']).optional(),
  from: z.coerce.date().optional(),
  to: z.coerce.date().optional(),
  page: z.coerce.number().int().positive().max(100_000).default(1),
  pageSize: z.coerce.number().int().positive().max(100).default(20),
});
export type SaleListQuery = z.infer<typeof saleListQuerySchema>;

export const createSaleReturnSchema = z.object({
  items: z
    .array(z.object({ saleItemId: z.string().trim().min(1), quantity: quantityString }))
    .min(1, 'Select at least one item to return')
    .max(200),
  refundMethod: z.enum(saleTenderMethods),
  reason: z.string().trim().max(300).optional(),
});
export type CreateSaleReturnInput = z.infer<typeof createSaleReturnSchema>;

export const receiptFormats = ['58mm', '80mm', 'a4'] as const;
export type ReceiptFormat = (typeof receiptFormats)[number];
export const receiptQuerySchema = z.object({
  format: z.enum(receiptFormats).default('80mm'),
});
export type ReceiptQuery = z.infer<typeof receiptQuerySchema>;

export const posProductSearchSchema = z.object({
  storeId: z.string().trim().min(1),
  search: z.string().trim().min(1).max(120),
});
export type PosProductSearchQuery = z.infer<typeof posProductSearchSchema>;

export const voucherKinds = ['DISCOUNT', 'CREDIT_MEMO'] as const;

export const issueVoucherSchema = z.object({
  kind: z.enum(voucherKinds),
  amount: moneyString.refine((v) => /[1-9]/.test(v), 'Amount must be greater than zero'),
  /** Leave empty to have one generated. */
  code: voucherCode.optional(),
  expiresAt: z.coerce.date().optional(),
  note: z.string().trim().max(200).optional(),
});
export type IssueVoucherInput = z.infer<typeof issueVoucherSchema>;

export const voucherListQuerySchema = z.object({
  kind: z.enum(voucherKinds).optional(),
  status: z.enum(['ACTIVE', 'USED', 'CANCELLED']).optional(),
  search: z.string().trim().max(40).optional(),
  page: z.coerce.number().int().positive().max(100_000).default(1),
  pageSize: z.coerce.number().int().positive().max(100).default(20),
});
export type VoucherListQuery = z.infer<typeof voucherListQuerySchema>;

export const voucherCodeParamSchema = z.object({ code: voucherCode });
